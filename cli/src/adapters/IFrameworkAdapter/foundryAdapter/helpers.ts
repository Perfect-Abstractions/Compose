import { withComposeProjectScripts } from "../../../modules/init/projectScripts";
import { CLI_DEV_DEPENDENCY_VERSION, CLI_PACKAGE_NAME } from "../../../utils/metadata";

/** Adds missing settings to a TOML section without overwriting existing values. */
export function ensureTomlSectionSettings(
  content: string,
  section: string,
  settings: Record<string, string>,
): string {
  const lines = content.replace(/\r\n/g, "\n").split("\n");
  if (lines.at(-1) === "") lines.pop();

  let sectionIndex = lines.findIndex((line) => line.trim() === `[${section}]`);
  if (sectionIndex === -1) {
    if (lines.length > 0 && lines.at(-1)?.trim() !== "") lines.push("");
    sectionIndex = lines.length;
    lines.push(`[${section}]`);
  }

  let sectionEnd = lines.findIndex(
    (line, index) => index > sectionIndex && /^\s*\[[^\]]+\]\s*$/.test(line),
  );
  if (sectionEnd === -1) sectionEnd = lines.length;

  const sectionLines = lines.slice(sectionIndex + 1, sectionEnd);
  const missingSettings = Object.entries(settings)
    .filter(([key]) => !sectionLines.some((line) => new RegExp(`^\\s*${key}\\s*=`).test(line)))
    .map(([key, value]) => `${key} = ${value}`);

  lines.splice(sectionEnd, 0, ...missingSettings);
  return `${lines.join("\n")}\n`;
}

/**
 * Builds the `package.json` written into generated Foundry projects.
 *
 * The manifest exposes native Foundry commands alongside the Compose
 * validate workflow, and declares the Compose CLI as a dev dependency so
 * project scripts run the local CLI instead of a global install.
 *
 * @param projectName - Name recorded in the generated package manifest.
 * @returns Pretty-printed package.json content with a trailing newline.
 */
export function buildFoundryPackageJson(projectName: string): string {
  const packageJson = {
    name: projectName,
    version: "0.1.0",
    private: true,
    description: "Diamond project generated by Compose CLI",
    scripts: withComposeProjectScripts({
      build: "forge build",
      test: "forge test",
      fmt: "forge fmt",
    }),
    devDependencies: {
      [CLI_PACKAGE_NAME]: CLI_DEV_DEPENDENCY_VERSION,
    },
  };

  return `${JSON.stringify(packageJson, null, 2)}\n`;
}

/**
 * Ensures a `.gitignore` entry exists without touching existing content.
 *
 * @param content - Current `.gitignore` content (may be empty).
 * @param entry - Entry to add when it is not already listed.
 * @returns The content unchanged, or with the entry appended on its own line.
 */
export function ensureGitignoreEntry(content: string, entry: string): string {
  const lines = content.split(/\r?\n/).map((line) => line.trim());
  if (lines.includes(entry)) return content;

  const separator = content === "" || content.endsWith("\n") ? "" : "\n";
  return `${content}${separator}${entry}\n`;
}
